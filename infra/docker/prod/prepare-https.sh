#!/bin/sh
set -eu

dir=infra/docker/prod
. "$dir/.env"

host_ip="$TLS_HOST_IP"
[ -n "$host_ip" ] || { echo 'Set TLS_HOST_IP to the machine IPv4 address in prod/.env.' >&2; exit 1; }

mkdir -p "$dir/tls"
cert="$dir/tls/server.crt"
key="$dir/tls/server.key"
if [ ! -s "$key" ] || ! "$OPENSSL_BIN" verify -CAfile "$cert" -verify_ip "$host_ip" "$cert" >/dev/null 2>&1; then
    "$OPENSSL_BIN" req -x509 -newkey rsa:2048 -nodes -sha256 -days 365 \
        -keyout "$key" -out "$cert" -subj "/CN=$host_ip" \
        -addext "subjectAltName=IP:$host_ip" \
        -addext 'basicConstraints=critical,CA:FALSE' \
        -addext 'extendedKeyUsage=serverAuth'
fi

fingerprint=$("$OPENSSL_BIN" x509 -in "$cert" -noout -fingerprint -sha256)
cat >"$dir/.env.https" <<EOF
# Generated by prepare-https.sh; do not edit or commit.
FRONTEND_ORIGIN=https://$host_ip:8443
S3_PUBLIC_ENDPOINT=https://$host_ip:9443
TLS_CERT_SHA256=${fingerprint#*=}
EOF
printf 'Application: https://%s:8443\nMedia: https://%s:9443\nCertificate: %s\n' "$host_ip" "$host_ip" "$cert"
